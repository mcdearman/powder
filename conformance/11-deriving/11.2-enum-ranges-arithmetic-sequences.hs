-- Haskell 2010 Report 11.2: derived Enum: enumFrom, enumFromThen, enumFromTo, enumFromThenTo and the [a ..] syntax;
-- enumFrom and enumFromThen stop at the last (or first, when descending) constructor
module Main (main) where

data Color = Red | Orange | Yellow | Green | Blue | Indigo | Violet deriving (Eq, Ord, Show, Enum)

main :: IO ()
main = do
  print ("[Red ..]", [Red ..])
  print ("[Green ..]", [Green ..])
  print ("[Violet ..]", [Violet ..])
  print ("enumFrom", enumFrom Indigo, enumFrom Red == [Red ..])
  print ("[Red, Yellow ..]", [Red, Yellow ..])
  print ("[Red, Orange ..]", [Red, Orange ..])
  print ("[Orange, Green ..]", [Orange, Green ..])
  print ("[Red, Violet ..]", [Red, Violet ..])
  print ("[Blue, Violet ..]", [Blue, Violet ..])
  print ("descending [Yellow, Orange ..]", [Yellow, Orange ..])
  print ("descending [Violet, Indigo ..]", [Violet, Indigo ..])
  print ("descending [Violet, Blue ..]", [Violet, Blue ..])
  print ("descending [Blue, Yellow ..]", [Blue, Yellow ..])
  print ("descending [Orange, Red ..]", [Orange, Red ..])
  print ("descending [Violet, Red ..]", [Violet, Red ..])
  print ("constant step is infinite", take 4 [Green, Green ..], take 2 (enumFromThen Red Red))
  print ("enumFromThen", enumFromThen Red Green, enumFromThen Violet Green)
  print ("[Orange .. Blue]", [Orange .. Blue])
  print ("[Red .. Violet]", [Red .. Violet] == [Red ..], length [Red .. Violet])
  print ("singleton and empty ranges", [Green .. Green], [Blue .. Yellow], [Violet .. Red])
  print ("enumFromTo", enumFromTo Red Yellow, enumFromTo Indigo Violet)
  print ("[Red, Yellow .. Violet]", [Red, Yellow .. Violet])
  print ("[Red, Yellow .. Indigo]", [Red, Yellow .. Indigo])
  print ("[Red, Yellow .. Red]", [Red, Yellow .. Red])
  print ("[Orange, Blue .. Violet]", [Orange, Blue .. Violet])
  print ("descending [Violet, Blue .. Red]", [Violet, Blue .. Red])
  print ("descending [Violet, Blue .. Orange]", [Violet, Blue .. Orange])
  print ("descending [Indigo, Blue .. Yellow]", [Indigo, Blue .. Yellow])
  print ("wrong direction is empty", [Red, Yellow .. Violet] /= [], [Yellow, Red .. Violet], [Yellow, Blue .. Red])
  print ("limit not hit exactly", [Red, Green .. Indigo], [Violet, Green .. Orange])
  print ("enumFromThenTo", enumFromThenTo Red Orange Green, enumFromThenTo Green Yellow Red)
  print ("constant step with limit", take 3 [Green, Green .. Violet], [Green, Green .. Red])
  print ("list functions on ranges", length [Red ..], last [Orange ..], zip [Red ..] "abc", map fromEnum [Red, Green ..])
  print ("comprehension", [(a, b) | a <- [Red .. Yellow], b <- [a ..], fromEnum b - fromEnum a == 4])
