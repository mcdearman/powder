-- Haskell 2010 Report 6.3.3: show, shows, showsPrec, showString, showChar, showParen; negative numbers at precedence > 6
main :: IO ()
main = do
  putStrLn (show (42 :: Int))
  putStrLn (shows (42 :: Int) " rest")
  putStrLn (showsPrec 0 (42 :: Int) "!")
  putStrLn ("prec 0 negative Int: " ++ showsPrec 0 (-5 :: Int) "")
  putStrLn ("prec 6 negative Int: " ++ showsPrec 6 (-5 :: Int) "")
  putStrLn ("prec 7 negative Int: " ++ showsPrec 7 (-5 :: Int) "")
  putStrLn ("prec 11 negative Int: " ++ showsPrec 11 (-5 :: Int) "")
  putStrLn ("prec 11 positive Int: " ++ showsPrec 11 (5 :: Int) "")
  putStrLn ("prec 6 negative Integer: " ++ showsPrec 6 (-12345678901234567890 :: Integer) "")
  putStrLn ("prec 7 negative Integer: " ++ showsPrec 7 (-12345678901234567890 :: Integer) "")
  putStrLn ("prec 11 zero: " ++ showsPrec 11 (0 :: Integer) "")
  putStrLn (showString "abc" "def")
  putStrLn (showChar 'x' "yz")
  putStrLn (showParen True (showString "inner") "")
  putStrLn (showParen False (showString "inner") "!")
  putStrLn (showParen True (showParen True (shows 'c')) "")
  putStrLn ((showString "a" . showChar 'b' . shows (1 :: Int) . showParen True (shows True)) "")
  putStrLn (foldr (\x acc -> shows x . showChar ';' . acc) id [1, 2, 3 :: Int] "")
  print ("show x == shows x \"\"", show (Just 'a') == shows (Just 'a') "", show "s" == shows "s" "")
  print ("shows == showsPrec 0", shows (-1 :: Int) "z" == showsPrec 0 (-1 :: Int) "z")
  print ("showsPrec appends", showsPrec 11 (Just True) "tail", showsPrec 0 [LT] "tail")
  print ("basic types", show True, show 'c', show "s", show (), show LT, show (1.5 :: Double))
  print ("numbers", show (0 :: Int), show (-7 :: Int), show (2 ^ (64 :: Int) :: Integer), show (minBound :: Int))
  print ("containers", show [1, 2 :: Int], show (1 :: Int, 'a'), show (Just 'x'), show (Left 1 :: Either Int Bool))
  print ("empty containers", show ([] :: [Int]), show "", show (Nothing :: Maybe Int), show [[] :: [Int]])
  print ("no spaces after commas", show [(1 :: Int, True)], show ([1 :: Int], [()], "x"))
