-- Haskell 2010 Report 6.3.2: Ord instances of the standard types; lexicographic ordering on lists and tuples
import Data.Ratio ((%))

main :: IO ()
main = do
  print ("Bool", False < True, compare True False, compare False False, max False True, True >= True)
  print ("Char", 'a' < 'b', 'Z' < 'a', '0' < 'A', compare ' ' '~', compare 'a' 'a', '\n' < ' ')
  print ("Int", (1 :: Int) < 2, (-1 :: Int) < 0, compare (minBound :: Int) maxBound, (3 :: Int) >= 3)
  print ("Integer", (2 :: Integer) ^ (64 :: Int) > 2 ^ (63 :: Int), compare (negate (10 :: Integer) ^ (21 :: Int)) 0)
  print ("Double", (1.5 :: Double) < 2, (-0.5 :: Double) < 0, compare (2.5 :: Double) 2.5, (1 / 0 :: Double) > 1.0e308)
  print ("Float", (1.5 :: Float) <= 1.5, compare (0.1 :: Float) 0.2, max (1 :: Float) 2)
  print ("Rational", (1 % 3 :: Rational) < 1 % 2, compare (2 % 4) (1 % 2 :: Rational), ((-1) % 2 :: Rational) < 0)
  print ("unit", compare () (), () <= (), () < ())
  print ("Ordering", LT < EQ, EQ < GT, compare GT LT, maximum [EQ, GT, LT])
  print ("Maybe", Nothing < Just 'a', Just 'a' < Just 'b', compare (Just 'a') Nothing, compare (Nothing :: Maybe ()) Nothing)
  print ("Either", (Left 'z' :: Either Char Char) < Right 'a', compare (Right 1) (Right 2 :: Either () Int), (Left 2 :: Either Int ()) > Left 1)
  print ("String", "apple" < "banana", "app" < "apple", "Zebra" < "apple", compare "same" "same", "" < "a")
  print ("list lexicographic", [1, 2, 3] < [1, 2, 4 :: Int], [1, 2] < [1, 2, 0 :: Int], [2] > [1, 100 :: Int])
  print ("list compare", compare [1, 2] [1, 2 :: Int], compare ([] :: [Int]) [], compare [[1], [2]] [[1], [1, 5 :: Int]])
  print ("tuple lexicographic", (1 :: Int, 'z') < (2, 'a'), (1 :: Int, 'a') < (1, 'b'), compare (1 :: Int, 'b', True) (1, 'b', False))
  print ("tuple max/min", max (1 :: Int, 'a') (1, 'b'), min (2 :: Int, 'a') (1, 'z'))
  print ("nested", [(1 :: Int, "b")] < [(1, "c")], Just [1, 2 :: Int] > Just [1], (Just 'a', [LT]) < (Just 'a', [EQ]))
  print ("decided by first difference", [1, undefined] < [2, undefined :: Int], compare (1 :: Int, undefined :: Int) (2, undefined))
  print ("infinite lists", [(1 :: Int) ..] < [2 ..], compare [(1 :: Int) ..] [1, 2, 0])
  print ("precedence", 1 + 2 < 2 * (2 :: Int), (1 :: Int) < 2 && (2 :: Int) < 3, not ((1 :: Int) >= 2))
