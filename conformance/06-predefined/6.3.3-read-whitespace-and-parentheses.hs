-- Haskell 2010 Report 6.3.3: read ignores surrounding white space and accepts redundant parentheses
main :: IO ()
main = do
  print ("leading/trailing space", read "  42" :: Int, read "42  " :: Int, read "\t42\n" :: Int, read " \n 42 \n " :: Int)
  print ("parens", read "(42)" :: Int, read "((42))" :: Int, read "( 42 )" :: Int, read " ( ( 42 ) ) " :: Int)
  print ("negative in parens", read "(-42)" :: Int, read " ( -42 ) " :: Int, read "((-42))" :: Int)
  print ("Double", read " 2.5 " :: Double, read "(2.5)" :: Double, read "( -2.5 )" :: Double)
  print ("Bool", read " True " :: Bool, read "(False)" :: Bool, read "( ( True ) )" :: Bool)
  print ("Char and String", read " 'x' " :: Char, read "('x')" :: Char, read " \"a b\" " :: String, read "(\"s\")" :: String)
  print ("space inside string kept", read "\"  a  \"" :: String, length (read " \" \" " :: String))
  print ("unit", read " () " :: (), read "(())" :: ())
  print ("list", read " [ 1 , 2 ,3 ] " :: [Int], read "([1,2])" :: [Int], read "[ ]" :: [Int], read "[(1),((2))]" :: [Int])
  print ("tuple", read " ( 1 , True ) " :: (Int, Bool), read "((1,True))" :: (Int, Bool), read "((1),(True))" :: (Int, Bool))
  print ("Maybe", read " Just 3 " :: Maybe Int, read "(Just 3)" :: Maybe Int, read "Just (3)" :: Maybe Int, read " ( Just ( 3 ) ) " :: Maybe Int)
  print ("Maybe no space before paren", read "Just(3)" :: Maybe Int, read "Just[1]" :: Maybe [Int])
  print ("Nothing", read " Nothing " :: Maybe Int, read "(Nothing)" :: Maybe Int, read "Just (Nothing)" :: Maybe (Maybe Int))
  print ("Either", read " Left  1 " :: Either Int Bool, read "(Right (True))" :: Either Int Bool)
  print ("Ordering", read " LT " :: Ordering, read "(GT)" :: Ordering)
  print ("newlines between tokens", read "[1,\n 2,\n 3]" :: [Int], read "Just\n5" :: Maybe Int)
  print ("reads keeps trailing text", reads " 1 2" :: [(Int, String)], reads "(1) x" :: [(Int, String)])
  print ("reads on trailing space", reads "7  " :: [(Int, String)], reads " [ ] ." :: [([Int], String)])
  print ("reads tuple then rest", reads "(1,'a')(2,'b')" :: [((Int, Char), String)])
