-- Haskell 2010 Report 6.1.2 (and 2.6): numeric character escapes in decimal, octal (\o) and hexadecimal (\x)
main :: IO ()
main = do
  print ("decimal", map fromEnum ['\65', '\0', '\127', '\255', '\1234', '\1114111'])
  print ("octal", map fromEnum ['\o101', '\o0', '\o177', '\o377', '\o4177777'])
  print ("hex", map fromEnum ['\x41', '\x0', '\x7f', '\xFF', '\x10FFFF', '\x10ffff'])
  print ("leading zeros", map fromEnum ['\0065', '\o000101', '\x0041'])
  print ("same char", '\65' == 'A', '\o101' == 'A', '\x41' == 'A')
  print ("decimal is greedy", map fromEnum "\0655")
  print ("decimal then empty escape", map fromEnum "\65\&5")
  print ("octal stops at 8", map fromEnum "\o1018")
  print ("hex stops at G", map fromEnum "\x41G")
  print ("hex is greedy", map fromEnum "\x41a")
  print ("hex then empty escape", map fromEnum "\x41\&a")
  print ("mixed string", "\72\x65\o154\108\x6f")
  print ("escape then space", map fromEnum "\65 5")
  print ("in the middle", "a\66c", length "a\66c")
  print ("max char", '\1114111' == (maxBound :: Char), '\x10FFFF' == maxBound)
