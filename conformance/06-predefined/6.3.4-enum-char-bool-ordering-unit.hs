-- Haskell 2010 Report 6.3.4: Enum at Char, Bool, Ordering and (); bounded enumerations stop at minBound/maxBound
main :: IO ()
main = do
  print ("char succ/pred", succ 'a', pred 'b', succ 'z', pred 'A', succ '9', pred 'a')
  print ("char codes", fromEnum 'a', toEnum 97 :: Char, fromEnum '\0', fromEnum (maxBound :: Char), fromEnum ' ')
  print ("char enumFromTo", ['a' .. 'f'], ['f' .. 'a'], ['x' .. 'x'], ['0' .. '9'])
  print ("char enumFromThenTo", ['a', 'c' .. 'k'], ['a', 'c' .. 'j'], ['z', 'x' .. 'q'], ['a', 'b' .. 'a'], ['b', 'a' .. 'c'])
  print ("char enumFrom", take 3 ['x' ..], length ['\1114109' ..], last ['\1114109' ..] == maxBound)
  print ("char enumFromThen up", take 3 ['a', 'c' ..], length ['\1114100', '\1114105' ..])
  print ("char enumFromThen down", length ['c', 'b' ..], last ['c', 'b' ..] == minBound, take 3 ['z', 'x' ..])
  print ("char method forms", enumFromTo 'a' 'c', enumFromThenTo 'a' 'd' 'm', map fromEnum "AZ")
  print ("char round trip", map (toEnum . (+ 1) . fromEnum) "HAL" :: String)
  print ("bool succ/pred", succ False, pred True)
  print ("bool codes", fromEnum False, fromEnum True, toEnum 0 :: Bool, toEnum 1 :: Bool)
  print ("bool enumFrom", [False ..], [True ..])
  print ("bool enumFromTo", [False .. True], [True .. False], [True .. True])
  print ("bool enumFromThen", [False, True ..], [True, False ..], take 2 [False, False ..])
  print ("bool enumFromThenTo", [False, True .. True], [True, False .. False], [False, True .. False], [True, False .. True])
  print ("ordering succ/pred", succ LT, succ EQ, pred GT, pred EQ)
  print ("ordering codes", map fromEnum [LT, EQ, GT], toEnum 2 :: Ordering)
  print ("ordering ranges", [LT ..], [EQ ..], [LT .. EQ], [GT .. LT], [LT, GT ..], [GT, EQ ..])
  print ("ordering enumFromThenTo", [LT, EQ .. GT], [LT, GT .. GT], [GT, EQ .. EQ], [GT, LT .. EQ])
  print ("unit", fromEnum (), toEnum 0 :: (), [() ..], [() .. ()], take 2 [(), () ..])
