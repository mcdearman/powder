-- Haskell 2010 Report 6.3.4: Enum at Double; numericEnumFromTo stops at limit + 1/2, numericEnumFromThenTo at limit + step/2
-- Element values are printed only for steps that are exact in binary; for 0.1 steps only the length is printed.
ds :: [Double] -> [Double]
ds = id

main :: IO ()
main = do
  print ("succ/pred", succ (1.5 :: Double), pred (1.5 :: Double), succ (-0.5 :: Double))
  print ("toEnum/fromEnum", toEnum 3 :: Double, fromEnum (3.7 :: Double), fromEnum (-3.7 :: Double), fromEnum (4.0 :: Double))
  print ("[1.0..5.0]", ds [1.0 .. 5.0])
  print ("[1.0..2.5] includes 3.0", ds [1.0 .. 2.5])
  print ("[1.0..2.4]", ds [1.0 .. 2.4])
  print ("[1.0..2.6]", ds [1.0 .. 2.6])
  print ("[1.0..1.4]", ds [1.0 .. 1.4])
  print ("[1.0..1.5]", ds [1.0 .. 1.5])
  print ("[1.0..1.0]", ds [1.0 .. 1.0])
  print ("[1.0..0.5] still has 1.0", ds [1.0 .. 0.5])
  print ("[1.0..0.6]", ds [1.0 .. 0.6])
  print ("[1.0..0.4] empty", ds [1.0 .. 0.4])
  print ("[3.0..1.0] empty", ds [3.0 .. 1.0])
  print ("[1.5..4.0]", ds [1.5 .. 4.0])
  print ("[0.5..3.0]", ds [0.5 .. 3.0])
  print ("[-1.5..1.0]", ds [-1.5 .. 1.0])
  print ("[1.0,1.5..3.0]", ds [1.0, 1.5 .. 3.0])
  print ("[1.0,1.5..3.1]", ds [1.0, 1.5 .. 3.1])
  print ("[1.0,1.5..3.25] includes 3.5", ds [1.0, 1.5 .. 3.25])
  print ("[1.0,1.5..3.2]", ds [1.0, 1.5 .. 3.2])
  print ("[1.0,3.0..8.0] includes 9.0", ds [1.0, 3.0 .. 8.0])
  print ("[1.0,3.0..7.9]", ds [1.0, 3.0 .. 7.9])
  print ("[5.0,3.0..0.0] includes -1.0", ds [5.0, 3.0 .. 0.0])
  print ("[5.0,3.0..0.5]", ds [5.0, 3.0 .. 0.5])
  print ("[10.0,7.5..0.0]", ds [10.0, 7.5 .. 0.0])
  print ("[5.0,4.0..1.0]", ds [5.0, 4.0 .. 1.0])
  print ("[1.0,2.0..0.0] empty", ds [1.0, 2.0 .. 0.0])
  print ("[1.0,0.0..2.0] empty", ds [1.0, 0.0 .. 2.0])
  print ("[3.0,3.0..2.0] empty", ds [3.0, 3.0 .. 2.0])
  print ("[1.0,1.0..2.0] infinite", take 3 (ds [1.0, 1.0 .. 2.0]))
  print ("enumFrom", take 4 (ds [0.5 ..]), take 3 (enumFrom (-1.25 :: Double)))
  print ("enumFromThen", take 4 (ds [1.0, 0.75 ..]), take 3 (enumFromThen 0 (0.5 :: Double)))
  print ("length [0.1,0.2..1.0]", length (ds [0.1, 0.2 .. 1.0]))
  print ("length [0.0,0.1..1.0]", length (ds [0.0, 0.1 .. 1.0]))
  print ("length [0.1..10.0]", length (ds [0.1 .. 10.0]))
  print ("method forms", enumFromTo 1 (3.5 :: Double), enumFromThenTo 0 0.25 (1 :: Double))
  print ("integer literals in a Double range", ds [1 .. 3], sum (ds [1 .. 100]))
