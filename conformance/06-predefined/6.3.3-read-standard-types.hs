-- Haskell 2010 Report 6.3.3: read at the standard types (Int, Integer, Double, Bool, Char, String, (), Ordering, lists, tuples, Maybe, Either)
main :: IO ()
main = do
  print ("Int", read "42" :: Int, read "-42" :: Int, read "0" :: Int, read "007" :: Int)
  print ("Int bounds", read "9223372036854775807" :: Int, read "-9223372036854775808" :: Int)
  print ("Integer", read "123456789012345678901234567890" :: Integer, read "-5" :: Integer)
  print ("Double", read "3.5" :: Double, read "3" :: Double, read "-2.5" :: Double, read "0.125" :: Double)
  print ("Double exponent", read "1e3" :: Double, read "1.5e2" :: Double, read "2.5e-1" :: Double, read "1.0E2" :: Double)
  print ("Float", read "0.5" :: Float, read "-1.25" :: Float, read "100" :: Float)
  print ("Bool", read "True" :: Bool, read "False" :: Bool)
  print ("Char", read "'a'" :: Char, read "'\\n'" :: Char, read "'\\''" :: Char, read "'\"'" :: Char, read "'\\65'" :: Char)
  print ("String", read "\"hi\"" :: String, read "\"a\\nb\"" :: String, read "\"\"" :: String, read "\"q\\\"q\"" :: String)
  print ("String escapes", read "\"\\SOH\\SO\\&H\\1234\\&5\\x41\\o101\"" :: String)
  print ("unit", read "()" :: ())
  print ("Ordering", read "LT" :: Ordering, read "EQ" :: Ordering, read "GT" :: Ordering)
  print ("list", read "[1,2,3]" :: [Int], read "[]" :: [Int], read "[[1],[2,3],[]]" :: [[Int]])
  print ("list of strings", read "[\"a\",\"b c\"]" :: [String], read "\"abc\"" :: [Char])
  print ("list of chars in string form", read "\"ab\"" :: String, read "[\"ab\",\"\"]" :: [String])
  print ("tuple", read "(1,True)" :: (Int, Bool), read "(1,'c',\"s\")" :: (Int, Char, String))
  print ("nested tuple", read "((1,2),[(3,4)])" :: ((Int, Int), [(Int, Int)]))
  print ("Maybe", read "Just 3" :: Maybe Int, read "Nothing" :: Maybe Int, read "Just \"s\"" :: Maybe String)
  print ("Either", read "Left 1" :: Either Int Bool, read "Right True" :: Either Int Bool)
  print ("compound", read "[Just (1,'a'),Nothing]" :: [Maybe (Int, Char)])
  print ("negative components", read "[-1,2,-3]" :: [Int], read "(-1,-2.5)" :: (Int, Double), read "Just (-7)" :: Maybe Int)
  print ("reads leaves the rest", reads "12 abc" :: [(Int, String)], reads "True&False" :: [(Bool, String)])
  print ("readsPrec", readsPrec 0 "5 x" :: [(Int, String)], readsPrec 11 "Just 5" :: [(Maybe Int, String)])
  print ("readsPrec with parens", readsPrec 11 "(Just 5) x" :: [(Maybe Int, String)])
  print ("readList", readList "[1,2] x" :: [([Int], String)], readList "\"ab\" x" :: [(String, String)])
  print ("read . show", read (show [(1 :: Int, Just 'c', "s\n")]) == [(1 :: Int, Just 'c', "s\n")])
  print ("read . show numbers", (read (show (-1.5e-3 :: Double)) :: Double) == (-1.5e-3), (read (show (minBound :: Int)) :: Int) == minBound)
