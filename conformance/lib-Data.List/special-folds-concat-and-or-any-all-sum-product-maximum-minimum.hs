-- Haskell 2010 Report 20.3.1 (Data.List): special folds concat, concatMap, and, or, any, all, sum, product,
-- maximum, minimum
module Main (main) where

import Data.List

main :: IO ()
main = do
  print ("concat", concat [[1, 2], [], [3], [4, 5 :: Int]])
  print ("concat empty", concat ([] :: [[Int]]))
  print ("concat of empties", concat ["", "", ""])
  print ("concat strings", concat ["ab", "cd", "e"])
  print ("concat infinite", take 5 (concat (repeat [1, 2 :: Int])))
  print ("concat lazy in later lists", take 2 (concat [[1, 2 :: Int], undefined]))
  print ("concatMap", concatMap (\x -> [x, x * 10]) [1, 2, 3 :: Int])
  print ("concatMap empty results", concatMap (\x -> if even x then [x] else []) [1 .. 10 :: Int])
  print ("concatMap show", concatMap show [1, 22, 333 :: Int])
  print ("concatMap empty", concatMap show ([] :: [Int]))
  print ("concatMap infinite", take 6 (concatMap (replicate 2) [1 :: Int ..]))
  print ("and", and [True, True], and [True, False], and [])
  print ("and short circuits", and (False : repeat True))
  print ("or", or [False, False], or [False, True], or [])
  print ("or short circuits", or (cycle [False, True]))
  print ("any", any even [1, 3, 5 :: Int], any even [1, 4, 5 :: Int], any even ([] :: [Int]))
  print ("any infinite", any (> 100) [1 :: Int ..])
  print ("all", all even [2, 4 :: Int], all even [2, 3 :: Int], all even ([] :: [Int]))
  print ("all infinite", all (< 100) [1 :: Int ..])
  print ("sum", sum [1, 2, 3, 4 :: Int], sum ([] :: [Int]), sum [-5, 5 :: Int])
  print ("sum Integer", sum [1 .. 100 :: Integer], sum (map (2 ^) [0 .. 70 :: Int]) :: Integer)
  print ("sum Double", sum [0.5, 0.25, 0.25 :: Double])
  print ("product", product [1, 2, 3, 4 :: Int], product ([] :: [Int]), product [5, 0, 7 :: Int])
  print ("product Integer", product [1 .. 25 :: Integer])
  print ("product Double", product [0.5, 4, 2.5 :: Double])
  print ("maximum", maximum [3, 1, 4, 1, 5, 9, 2, 6 :: Int])
  print ("maximum singleton", maximum [7 :: Int])
  print ("maximum negatives", maximum [-3, -1, -2 :: Int])
  print ("maximum string", maximum "hello")
  print ("maximum of lists", maximum [[1, 2], [1, 3], [1 :: Int]])
  print ("maximum of pairs", maximum [(1, 'b'), (2, 'a'), (1, 'c')])
  print ("minimum", minimum [3, 1, 4, 1, 5, 9, 2, 6 :: Int])
  print ("minimum singleton", minimum [7 :: Int])
  print ("minimum string", minimum "hello")
  print ("minimum of lists", minimum [[1, 2], [1, 3], [1 :: Int]])
  print ("minimum of strings", minimum ["banana", "apple", "cherry"], maximum ["banana", "apple", "cherry"])
  print ("minimum of Double", minimum [0.5, -0.25, 2 :: Double], maximum [0.5, -0.25, 2 :: Double])
