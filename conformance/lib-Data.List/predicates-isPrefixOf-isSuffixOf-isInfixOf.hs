-- Haskell 2010 Report 20.5.2 (Data.List): predicates isPrefixOf, isSuffixOf, isInfixOf (empty needles,
-- infinite haystacks)
module Main (main) where

import Data.List

main :: IO ()
main = do
  print ("isPrefixOf", "ab" `isPrefixOf` "abc")
  print ("isPrefixOf equal", "abc" `isPrefixOf` "abc")
  print ("isPrefixOf longer", "abcd" `isPrefixOf` "abc")
  print ("isPrefixOf mismatch", "ac" `isPrefixOf` "abc")
  print ("isPrefixOf suffix is not prefix", "bc" `isPrefixOf` "abc")
  print ("isPrefixOf empty needle", "" `isPrefixOf` "abc")
  print ("isPrefixOf both empty", "" `isPrefixOf` "")
  print ("isPrefixOf empty haystack", "a" `isPrefixOf` "")
  print ("isPrefixOf infinite haystack", [1, 2, 3] `isPrefixOf` [1 :: Int ..])
  print ("isPrefixOf infinite mismatch", [1, 3] `isPrefixOf` [1 :: Int ..])
  print ("isPrefixOf infinite needle against finite", [1 :: Int ..] `isPrefixOf` [1, 2, 3])
  print ("isPrefixOf empty needle ignores haystack", ([] :: [Int]) `isPrefixOf` undefined)
  print ("isSuffixOf", "bc" `isSuffixOf` "abc")
  print ("isSuffixOf equal", "abc" `isSuffixOf` "abc")
  print ("isSuffixOf longer", "zabc" `isSuffixOf` "abc")
  print ("isSuffixOf mismatch", "ac" `isSuffixOf` "abc")
  print ("isSuffixOf prefix is not suffix", "ab" `isSuffixOf` "abc")
  print ("isSuffixOf empty needle", "" `isSuffixOf` "abc")
  print ("isSuffixOf both empty", "" `isSuffixOf` "")
  print ("isSuffixOf empty haystack", "a" `isSuffixOf` "")
  print ("isSuffixOf numbers", [4, 5] `isSuffixOf` [1, 2, 3, 4, 5 :: Int])
  print ("isSuffixOf repeated", "aa" `isSuffixOf` "baaa", "ab" `isSuffixOf` "abab")
  print ("isInfixOf", "ell" `isInfixOf` "hello")
  print ("isInfixOf prefix", "he" `isInfixOf` "hello")
  print ("isInfixOf suffix", "lo" `isInfixOf` "hello")
  print ("isInfixOf whole", "hello" `isInfixOf` "hello")
  print ("isInfixOf not contiguous", "hlo" `isInfixOf` "hello")
  print ("isInfixOf longer", "hello!" `isInfixOf` "hello")
  print ("isInfixOf empty needle", "" `isInfixOf` "hello")
  print ("isInfixOf both empty", "" `isInfixOf` "")
  print ("isInfixOf empty haystack", "a" `isInfixOf` "")
  print ("isInfixOf overlapping candidates", "aab" `isInfixOf` "aaab", "aba" `isInfixOf` "abba")
  print ("isInfixOf infinite haystack", [5, 6, 7] `isInfixOf` [1 :: Int ..])
  print ("isInfixOf words", "works" `isInfixOf` "Haskell works well", "Works" `isInfixOf` "Haskell works well")
  print ("prefix implies infix", all (\p -> p `isInfixOf` "abcd") (inits "abcd"))
  print ("suffix via reverse", all (\s -> isSuffixOf s "abcd" == isPrefixOf (reverse s) (reverse "abcd")) ["cd", "d", "", "bd", "abcd"])
  print ("fixity allows comparison", "a" `isPrefixOf` "ab" == True)
