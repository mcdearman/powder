-- Haskell 2010 Report 20.8 (Data.List): zip, zip3, zipWith, zipWith3, unzip, unzip3
module Main (main) where

import Data.List

main :: IO ()
main = do
  print ("zip", zip [1, 2, 3 :: Int] "abc")
  print ("zip left shorter", zip [1, 2 :: Int] "abc")
  print ("zip right shorter", zip [1, 2, 3 :: Int] "a")
  print ("zip empty left", zip ([] :: [Int]) "abc")
  print ("zip empty right", zip "abc" ([] :: [Int]))
  print ("zip infinite", zip [1 :: Int ..] "abc")
  print ("zip two infinite", take 3 (zip [1 :: Int ..] (cycle "xy")))
  print ("zip empty left ignores right", zip ([] :: [Int]) (undefined :: [Char]))
  print ("zip stops before undefined tail", zip [1 :: Int] ('a' : undefined))
  print ("zip with itself shifted", zip "abcd" (tail "abcd"))
  print ("zip3", zip3 [1, 2, 3 :: Int] "abc" [True, False, True])
  print ("zip3 uneven", zip3 [1, 2, 3 :: Int] "ab" [True])
  print ("zip3 empty", zip3 [1, 2, 3 :: Int] "" [True])
  print ("zip3 infinite", zip3 [1 :: Int ..] "ab" (repeat ()))
  print ("zipWith", zipWith (+) [1, 2, 3] [10, 20, 30 :: Int])
  print ("zipWith uneven", zipWith (+) [1, 2, 3] [10 :: Int])
  print ("zipWith empty", zipWith (+) [] [10 :: Int])
  print ("zipWith different types", zipWith replicate [1, 2, 3] "abc")
  print ("zipWith pairing is zip", zipWith (,) [1, 2 :: Int] "ab" == zip [1, 2] "ab")
  print ("zipWith infinite", take 5 (zipWith (*) [1 :: Int ..] [1 ..]))
  print ("zipWith does not force unused elements", length (zipWith (\_ _ -> ()) [undefined, undefined :: Int] "ab"))
  print ("zipWith adjacent differences", zipWith (-) (tail [1, 4, 9, 16, 25 :: Int]) [1, 4, 9, 16, 25])
  print ("zipWith3", zipWith3 (\a b c -> a + b * c) [1, 2, 3] [10, 20, 30] [2, 2, 2 :: Int])
  print ("zipWith3 uneven", zipWith3 (\a b c -> [a, b, c]) "abc" "de" "fghi")
  print ("zipWith3 tripling is zip3", zipWith3 (,,) [1 :: Int] "a" [True] == zip3 [1] "a" [True])
  print ("zipWith3 infinite", take 3 (zipWith3 (\a b c -> a + b + c) [1 :: Int ..] [10, 20 ..] [100, 200 ..]))
  print ("unzip", unzip [(1 :: Int, 'a'), (2, 'b'), (3, 'c')])
  print ("unzip empty", unzip ([] :: [(Int, Char)]))
  print ("unzip singleton", unzip [("only", True)])
  print ("unzip infinite", take 3 (fst (unzip (zip [1 :: Int ..] (repeat 'x')))))
  print ("unzip . zip", unzip (zip [1, 2, 3 :: Int] "abc") == ([1, 2, 3], "abc"))
  print ("zip after unzip", uncurry zip (unzip [(1 :: Int, 'a'), (2, 'b')]))
  print ("unzip3", unzip3 [(1 :: Int, 'a', True), (2, 'b', False)])
  print ("unzip3 empty", unzip3 ([] :: [(Int, Char, Bool)]))
  print ("unzip3 . zip3", unzip3 (zip3 [1, 2 :: Int] "ab" [LT, GT]) == ([1, 2], "ab", [LT, GT]))
