-- Haskell 2010 Report 20.2 (Data.List): list transformations map, reverse, intersperse, intercalate,
-- transpose (including ragged input)
module Main (main) where

import Data.List

main :: IO ()
main = do
  print ("map", map (* 2) [1, 2, 3 :: Int])
  print ("map empty", map (* 2) ([] :: [Int]))
  print ("map changes type", map show [1, 2, 3 :: Int])
  print ("map infinite", take 4 (map (^ (2 :: Int)) [1 :: Int ..]))
  print ("map is lazy in elements", length (map (\_ -> (undefined :: Int)) "abc"))
  print ("map composition", map (succ . succ) "abc" == map succ (map succ "abc"))
  print ("reverse", reverse [1, 2, 3 :: Int])
  print ("reverse empty", reverse ([] :: [Int]))
  print ("reverse singleton", reverse "x")
  print ("reverse string", reverse "stressed")
  print ("reverse twice", reverse (reverse "abc"))
  print ("intersperse", intersperse ',' "abcde")
  print ("intersperse empty", intersperse ',' "")
  print ("intersperse singleton", intersperse ',' "a")
  print ("intersperse two", intersperse 0 [1, 2 :: Int])
  print ("intersperse infinite", take 7 (intersperse 0 [1 :: Int ..]))
  print ("intersperse lists", intersperse [0] [[1], [2, 3 :: Int]])
  print ("intercalate", intercalate ", " ["Lorem", "ipsum", "dolor"])
  print ("intercalate empty list", intercalate ", " [])
  print ("intercalate singleton", intercalate ", " ["only"])
  print ("intercalate empty separator", intercalate "" ["ab", "cd"])
  print ("intercalate empty elements", intercalate "-" ["", "", ""])
  print ("intercalate numbers", intercalate [0, 0] [[1], [2, 3], [], [4 :: Int]])
  print ("intercalate is concat . intersperse", intercalate "ab" ["x", "y", "z"] == concat (intersperse "ab" ["x", "y", "z"]))
  print ("transpose", transpose ["abc", "def"])
  print ("transpose square", transpose [[1, 2], [3, 4 :: Int]])
  print ("transpose ragged", transpose ["abc", "de", "f"])
  print ("transpose ragged with empty rows", transpose [[1, 2, 3], [], [4, 5 :: Int]])
  print ("transpose ragged increasing", transpose ["a", "bc", "def"])
  print ("transpose empty", transpose ([] :: [[Int]]))
  print ("transpose all empty rows", transpose ["", "", ""])
  print ("transpose single row", transpose ["abc"])
  print ("transpose single column", transpose ["a", "b", "c"])
  print ("transpose twice on rectangle", transpose (transpose ["abc", "def"]))
  print ("transpose twice on ragged", transpose (transpose ["abc", "de", "f"]))
  print ("transpose infinite rows", take 3 (map (take 2) (transpose [[1 :: Int ..], [10 ..]])))
  print ("transpose infinitely many rows", take 3 (head (transpose (map (\n -> [n, n + 1]) [1 :: Int ..]))))
