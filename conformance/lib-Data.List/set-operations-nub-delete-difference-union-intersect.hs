-- Haskell 2010 Report 20.9.2 (Data.List): "set" operations nub, delete, (\\), union, intersect with the
-- Report's exact treatment of duplicates
module Main (main) where

import Data.List

main :: IO ()
main = do
  print ("nub", nub [1, 2, 1, 3, 2, 4, 1 :: Int])
  print ("nub keeps first occurrences", nub "mississippi")
  print ("nub empty", nub ([] :: [Int]))
  print ("nub no duplicates", nub "abc")
  print ("nub all equal", nub "aaaa")
  print ("nub pairs", nub [(1 :: Int, 'a'), (1, 'b'), (1, 'a')])
  print ("nub infinite", take 3 (nub (cycle [1, 2, 3 :: Int])))
  print ("nub idempotent", nub (nub "banana") == nub "banana")
  print ("delete", delete 3 [1, 2, 3, 4 :: Int])
  print ("delete only first occurrence", delete 'a' "banana")
  print ("delete missing", delete 9 [1, 2, 3 :: Int])
  print ("delete from empty", delete 'a' "")
  print ("delete last", delete 3 [1, 2, 3 :: Int])
  print ("delete from infinite", take 4 (delete 3 [1 :: Int ..]))
  print ("difference", [1, 2, 3, 4, 5] \\ [2, 4 :: Int])
  print ("difference removes first occurrences only", [1, 2, 1, 3] \\ [1 :: Int])
  print ("difference with duplicates on both sides", [1, 2, 3, 2, 1] \\ [2, 1, 2 :: Int])
  print ("difference with absent elements", "abc" \\ "xyz")
  print ("difference by empty", "abc" \\ "")
  print ("difference from empty", "" \\ "abc")
  print ("difference by itself", "abcabc" \\ "abcabc")
  print ("difference more copies removed than present", "aab" \\ "aaa")
  print ("difference undoes append", ("ab" ++ "cab") \\ "ab")
  print ("difference is not symmetric", "abcd" \\ "cd", "cd" \\ "abcd")
  print ("union", union [1, 2, 3] [3, 4, 5 :: Int])
  print ("union keeps duplicates of first", union [1, 1, 2] [2, 3, 3 :: Int])
  print ("union removes duplicates of second", union "ab" "ccdd")
  print ("union with empty first", union [] [1, 1, 2 :: Int])
  print ("union with empty second", union [1, 1, 2 :: Int] [])
  print ("union order", union "dcba" "abef")
  print ("union both empty", union ([] :: [Int]) [])
  print ("union operator form", "abc" `union` "bcd" `union` "cde")
  print ("intersect", intersect [1, 2, 3, 4] [2, 4, 6, 8 :: Int])
  print ("intersect keeps duplicates of first", intersect [1, 1, 2, 3] [1, 3, 3 :: Int])
  print ("intersect ignores duplicates of second", intersect [1, 2] [2, 2, 2 :: Int])
  print ("intersect disjoint", intersect "abc" "xyz")
  print ("intersect with empty", intersect "abc" "", intersect "" "abc")
  print ("intersect order follows first", intersect "dcba" "abcd")
  print ("intersect operator form", "abcd" `intersect` "bcde" `intersect` "cdef")
  print ("intersect with infinite second when all found", take 2 ([3, 5] `intersect` [1 :: Int ..]))
