-- Haskell 2010 Report 20.9.1 (Data.List): functions on strings lines, words, unlines, unwords
module Main (main) where

import Data.List

main :: IO ()
main = do
  print ("lines", lines "one\ntwo\nthree")
  print ("lines trailing newline", lines "one\ntwo\n")
  print ("lines empty", lines "")
  print ("lines only newline", lines "\n")
  print ("lines two newlines", lines "\n\n")
  print ("lines blank line in middle", lines "a\n\nb\n")
  print ("lines leading newline", lines "\na")
  print ("lines no newline", lines "single")
  print ("lines keeps carriage return", lines "a\r\nb")
  print ("lines keeps spaces", lines " a \n\tb ")
  print ("lines lazy", take 2 (lines (cycle "ab\n")))
  print ("lines first line of infinite", head (lines ("first\n" ++ repeat 'x')))
  print ("unlines", unlines ["one", "two"])
  print ("unlines empty", unlines [])
  print ("unlines one empty string", unlines [""])
  print ("unlines singleton", unlines ["a"])
  print ("unlines with embedded newline", unlines ["a\nb", "c"])
  print ("lines . unlines", lines (unlines ["a", "", "b"]))
  print ("unlines . lines adds final newline", unlines (lines "a\nb"))
  print ("unlines . lines idempotent with final newline", unlines (lines "a\nb\n") == "a\nb\n")
  print ("words", words "the quick  brown\tfox\njumps")
  print ("words leading and trailing space", words "  padded  ")
  print ("words empty", words "")
  print ("words only whitespace", words " \t\n\r\f\v ")
  print ("words single", words "word")
  print ("words punctuation stays", words "Hello, world! (yes)")
  print ("words all separators", words "a\tb\nc\rd\fe\vf g")
  print ("words lazy", take 3 (words (cycle "ab ")))
  print ("unwords", unwords ["the", "quick", "fox"])
  print ("unwords empty", unwords [])
  print ("unwords singleton", unwords ["one"])
  print ("unwords with empty strings", unwords ["", "a", "", "b", ""])
  print ("unwords does not add trailing space", last (unwords ["a", "b"]))
  print ("words . unwords", words (unwords ["a", "bc", "d"]))
  print ("unwords . words normalises space", unwords (words "  a   b \n c  "))
  print ("word count per line", map (length . words) (lines "a b c\n\nd e\n"))
  print ("reverse words", unwords (reverse (words "one two three")))
