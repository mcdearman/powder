-- Haskell 2010 Report 4.3.4: ambiguous numeric types resolved by the implicit default (Integer, Double)
module Main (main) where

import Data.Ix (inRange, range)

main :: IO ()
main = do
  putStrLn ("show pow: " ++ show (2 ^ 10))
  print ("big pow is Integer", 2 ^ 64)
  print ("literal", 7)
  print ("negative literal", -7)
  print ("fractional literal", 0.25)
  print ("division", 1 / 4)
  print ("third", 1 / 3)
  print ("mixed", 2 + 0.5)
  print ("div mod", 17 `div` 5, 17 `mod` 5)
  print ("fromIntegral to Double", fromIntegral (3 :: Int) + 0.5)
  print ("fromIntegral to Integer", fromIntegral (maxBound :: Int) + 1)
  print ("list", [1, 2, 3])
  print ("fractional list", [1, 2.5])
  print ("sum", sum [1, 2, 3])
  print ("product no overflow", product [1 .. 25])
  print ("sqrt", sqrt 16)
  print ("power", 2 ** 10)
  print ("eq", 3 == 3.0)
  print ("negate", negate 5)
  print ("read", read "41" + 1)
  print ("range", range (1, 4))
  print ("inRange", inRange (1, 5) 3)
  print ("length of big", length (show (2 ^ 100)))
  print ("even", even 10)
  print ("minimum", minimum [3, 1, 2])
  print ("realToFrac", realToFrac (1.5 :: Float) * 2)
  print ("gcd", gcd 12 18)
  print ("two variables", (2 ^ 3, 2 ** 3))
