-- Haskell 2010 Report 3.4: prefix negation; -e is negate e and binds like binary minus (precedence 6)
module Main (main) where

main :: IO ()
main = do
  let x = 5 :: Int
  print ("literal", -1)
  print ("variable", - x)
  print ("negate", negate x, - x == negate x)
  print ("-2^2", -2 ^ 2)
  print ("(-2)^2", (-2) ^ 2)
  print ("- 7 `mod` 3", - 7 `mod` 3)
  print ("(-7) `mod` 3", (-7) `mod` 3)
  print ("- 7 `div` 2", - 7 `div` 2)
  print ("(-7) `div` 2", (-7) `div` 2)
  print ("- 2 * 3", - 2 * 3)
  print ("- x + 1", - x + 1)
  print ("- x - 1", - x - 1)
  print ("1 - 2 - 3", 1 - 2 - 3)
  print ("(- 1) is a number", (- 1) + 10)
  print ("subtract 1", map (subtract 1) [1, 2, 3])
  print ("lambda minus", map (\n -> n - 1) [1, 2, 3])
  print ("abs", abs (-3), abs (- x))
  print ("double negation", - (- x), negate (negate x))
  print ("comparison", -1 < 0, - x < x, 0 > -1)
  print ("equality", 0 - 1 == -1, -1 == 0 - 1)
  print ("double", - 2.5, -0.5 + 1)
  print ("list", [-1, -2, - 3])
  print ("tuple", (-1, - x))
  print ("application operand", - abs x, - succ x * 2)
  print ("argument", succ (-1), max (-1) (-2))
  print ("let", let y = - x in y)
  print ("dollar", negate $ -3, abs $ - x)
  print ("minBound", -9223372036854775808 == (minBound :: Int))
  print ("integer", -123456789012345678901234567890)
