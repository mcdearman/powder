-- Haskell 2010 Report 3.10 / 6.3.4: arithmetic sequences at Double, Float and Rational (limit is e3 + step/2)
module Main (main) where

import Data.Ratio ((%))

main :: IO ()
main = do
  print ("from-to", [1.0 .. 5.0] :: [Double])
  print ("from-then-to", [1.0, 1.5 .. 3.0] :: [Double])
  print ("overshoot by half", [1.0 .. 5.5] :: [Double])
  print ("half offsets", [1.5 .. 4.0] :: [Double])
  print ("just below half", [1.0 .. 1.25] :: [Double])
  print ("exactly half", [1.0 .. 1.5] :: [Double])
  print ("step 2", [1, 3 .. 10.0] :: [Double])
  print ("descending", [5.0, 4.5 .. 3.0] :: [Double])
  print ("descending overshoot", [3.0, 2.0 .. 0.5] :: [Double])
  print ("empty", [5.0 .. 1.0] :: [Double])
  print ("empty then", [1.0, 2.0 .. 0.0] :: [Double])
  print ("single", [1.0 .. 1.0] :: [Double])
  print ("from", take 4 [0.5 ..] :: [Double])
  print ("from-then", take 3 [1.0, 0.75 ..] :: [Double])
  print ("quarters", [0.0, 0.25 .. 1.0] :: [Double])
  print ("length", length ([0.0, 0.125 .. 1.0] :: [Double]))
  print ("negative", [-1.0, -0.5 .. 1.0] :: [Double])
  print ("float", [1.0, 1.5 .. 3.0] :: [Float])
  print ("float from-to", [0.5 .. 3.0] :: [Float])
  print ("rational from-to", [1 % 2 .. 3] :: [Rational])
  print ("rational from-then-to", [0, 1 % 4 .. 1] :: [Rational])
  print ("rational from", take 3 [1 % 3 ..] :: [Rational])
  print ("integer literals", [1 .. 4] :: [Double])
