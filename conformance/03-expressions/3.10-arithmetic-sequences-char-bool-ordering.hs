-- Haskell 2010 Report 3.10: arithmetic sequences at Char, Bool, Ordering and ()
module Main (main) where

main :: IO ()
main = do
  print ("char from-to", ['a' .. 'e'])
  print ("char from-then-to", ['a', 'c' .. 'i'])
  print ("char descending", ['e', 'd' .. 'a'])
  print ("char empty", ['z' .. 'a'])
  print ("char single", ['a' .. 'a'])
  print ("char from", take 3 ['x' ..])
  print ("char from-then", take 3 ['a', 'c' ..])
  print ("char no spaces", ['a'..'e'], ['a','c'..'i'])
  print ("digits", ['0' .. '9'])
  print ("char count", length ['\0' .. '\255'])
  print ("char past limit", ['a', 'd' .. 'h'])
  print ("char from-then down", ['c', 'b' ..] == "cba" ++ reverse ['\0' .. '`'])
  print ("bool from", [False ..], [True ..])
  print ("bool from-to", [False .. True], [True .. False])
  print ("bool from-then", [False, True ..], [True, False ..])
  print ("ordering from", [LT ..], [EQ ..])
  print ("ordering from-then", [LT, GT ..], [GT, EQ ..])
  print ("ordering from-to", [LT .. GT], [GT .. LT])
  print ("ordering from-then-to", [GT, EQ .. LT], [LT, GT .. GT])
  print ("unit", [() ..], [() .. ()])
