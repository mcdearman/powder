-- Haskell 2010 Report 3.11: list comprehensions with nested generators (later generators vary fastest)
module Main (main) where

main :: IO ()
main = do
  print ("single", [x * 2 | x <- [1, 2, 3]])
  print ("two", [(x, y) | x <- [1, 2, 3], y <- "ab"])
  print ("order swapped", [(x, y) | y <- "ab", x <- [1, 2, 3]])
  print ("dependent", [(x, y) | x <- [1 .. 4], y <- [x .. 4]])
  print ("dependent count", length [() | x <- [1 .. 10], _ <- [1 .. x]])
  print ("three", [[a, b, c] | a <- "ab", b <- "cd", c <- "ef"])
  print ("pythagorean", [(a, b, c) | c <- [1 .. 20], b <- [1 .. c], a <- [1 .. b], a * a + b * b == c * c])
  print ("empty first", [(x, y) | x <- [], y <- [1, 2, 3]] :: [(Int, Int)])
  print ("empty second", [(x, y) | x <- [1, 2, 3], y <- []] :: [(Int, Int)])
  print ("flatten", [x | xs <- [[1, 2], [], [3]], x <- xs])
  print ("string source", [c | c <- "hello", c /= 'l'])
  print ("tuple source", [a + b | (a, b) <- zip [1, 2, 3] [10, 20, 30]])
  print ("result ignores vars", [0 | _ <- "abc"])
  print ("nested comprehension", [[x * y | y <- [1 .. 3]] | x <- [1 .. 3]])
  print ("transpose", [[row !! i | row <- [[1, 2, 3], [4, 5, 6]]] | i <- [0 .. 2]])
  print ("generator from comprehension", [y | y <- [x * x | x <- [1 .. 5]], odd y])
  print ("infinite outer needs take", take 4 [(x, y) | x <- [1 ..], y <- "ab"])
  print ("result function", map (\f -> f 1) [(+ n) | n <- [1, 2, 3]])
  print ("as argument", sum [x | x <- [1 .. 10]], length [x | x <- "abc", y <- "de"])
