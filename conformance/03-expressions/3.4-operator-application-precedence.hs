-- Haskell 2010 Report 3.4: infix operator applications resolved by the Prelude fixities
module Main (main) where

main :: IO ()
main = do
  print ("1 + 2 * 3", 1 + 2 * 3)
  print ("(1 + 2) * 3", (1 + 2) * 3)
  print ("2 ^ 3 ^ 2", 2 ^ 3 ^ 2)
  print ("(2 ^ 3) ^ 2", (2 ^ 3) ^ 2)
  print ("2 ^ 2 * 3", 2 ^ 2 * 3, 2 * 3 ^ 2)
  print ("10 - 3 - 2", 10 - 3 - 2)
  print ("10 - 3 + 2", 10 - 3 + 2)
  print ("div chain", 100 `div` 10 `div` 5)
  print ("2 * 3 `mod` 4", 2 * 3 `mod` 4)
  print ("7 / 2 / 2", 7 / 2 / 2)
  print ("2 ** 3 ** 2", 2 ** 3 ** 2)
  print ("cons/append", 1 : 2 : [] ++ [3])
  print ("append chain", "a" ++ "b" ++ "c")
  print ("or/and", True || False && False, (True || False) && False)
  print ("not", not True || True, not (True || True))
  print ("mixed", 1 + 2 == 3 && 4 < 5)
  print ("compare arith", 2 * 3 > 5, 1 + 1 /= 2)
  print ("elem", 1 + 1 `elem` [2], 3 `notElem` 1 : [2])
  print ("compose", (subtract 1 . (* 2) . (+ 3)) 4)
  print ("compose dollar", negate . abs $ -3)
  print ("dollar chain", map (+ 1) $ filter even $ [1 .. 6])
  print ("index chain", [[1, 2], [3, 4]] !! 1 !! 0)
  print ("index vs compose", (head . tail) [1, 2, 3], "abc" !! 1 : "z")
  print ("application first", succ 1 + succ 2 * succ 3)
  print ("seq", 1 `seq` 2 + 3)
  print ("bind", [1, 2] >>= \a -> [a, a * 10] >>= \b -> [b + 1])
  print ("then", [1, 2] >> "ab" >> [True])
  print ("neg after low op", 0 - 1 == -1, 1 < -1 || True)
  print ("strict apply", succ $! 1 + 1)
  print ("reverse bind", (\a -> [a, a]) =<< (\b -> [b + 1]) =<< [1, 2])
