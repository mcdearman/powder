-- Haskell 2010 Report 38.1 (Numeric): showInt, showHex, showOct, showIntAtBase (non-negative arguments)
module Main (main) where

import Data.Char (intToDigit, toUpper)
import Data.Word
import Numeric

base36 :: Int -> Char
base36 d
  | d < 10 = toEnum (fromEnum '0' + d)
  | otherwise = toEnum (fromEnum 'a' + d - 10)

main :: IO ()
main = do
  putStrLn (showInt (0 :: Int) "")
  putStrLn (showInt (42 :: Int) "")
  putStrLn (showInt (maxBound :: Int) "")
  putStrLn (showInt (12345678901234567890123 :: Integer) "")
  putStrLn (showInt (255 :: Word8) "")
  putStrLn (showInt (7 :: Int) " apples")
  putStrLn (showHex (0 :: Int) "")
  putStrLn (showHex (9 :: Int) "")
  putStrLn (showHex (10 :: Int) "")
  putStrLn (showHex (255 :: Int) "")
  putStrLn (showHex (256 :: Int) "")
  putStrLn (showHex (48879 :: Int) "")
  putStrLn (showHex (maxBound :: Int) "")
  putStrLn (showHex (maxBound :: Word64) "")
  putStrLn (showHex (2 ^ (100 :: Int) :: Integer) "")
  putStrLn (showHex (171 :: Word8) "h")
  putStrLn (showOct (0 :: Int) "")
  putStrLn (showOct (7 :: Int) "")
  putStrLn (showOct (8 :: Int) "")
  putStrLn (showOct (64 :: Int) "")
  putStrLn (showOct (493 :: Int) "")
  putStrLn (showOct (maxBound :: Int) "")
  putStrLn (showOct (2 ^ (66 :: Int) :: Integer) "")
  putStrLn (showIntAtBase 2 intToDigit (0 :: Int) "")
  putStrLn (showIntAtBase 2 intToDigit (10 :: Int) "")
  putStrLn (showIntAtBase 2 intToDigit (255 :: Int) "")
  putStrLn (showIntAtBase 2 intToDigit (maxBound :: Word16) "")
  putStrLn (showIntAtBase 3 intToDigit (26 :: Int) "")
  putStrLn (showIntAtBase 10 intToDigit (1234 :: Int) "")
  putStrLn (showIntAtBase 16 intToDigit (48879 :: Int) "")
  putStrLn (showIntAtBase 16 (toUpper . intToDigit) (48879 :: Int) "")
  putStrLn (showIntAtBase 36 base36 (1295 :: Int) "")
  putStrLn (showIntAtBase 36 base36 (46655 :: Int) "")
  putStrLn (showIntAtBase 5 (\d -> "abcde" !! d) (624 :: Integer) "")
  putStrLn (showIntAtBase 2 intToDigit (5 :: Int) " in binary")
  putStrLn ((showHex (255 :: Int) . showString " / " . showOct (255 :: Int) . showString " / " . showInt (255 :: Int)) "")
  print ("showInt is show", all (\n -> showInt n "" == show n) [0, 1, 9, 10, 99, 100, 123456 :: Int])
  print ("showHex is base 16", all (\n -> showHex n "" == showIntAtBase 16 intToDigit n "") [0, 15, 16, 255, 4096 :: Int])
  print ("showOct is base 8", all (\n -> showOct n "" == showIntAtBase 8 intToDigit n "") [0, 7, 8, 63, 64 :: Int])
  print ("hex digits of powers of 16", map (\k -> length (showHex ((16 :: Integer) ^ k) "")) [0 .. 5 :: Int])
