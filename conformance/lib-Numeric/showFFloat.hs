-- Haskell 2010 Report 38.1 (Numeric): showFFloat with Nothing and with Just n (n >= 1) digits after the
-- decimal point (no inputs that sit exactly on a rounding tie; see the -ghc-differs file for those)
module Main (main) where

import Numeric

f :: Maybe Int -> Double -> String
f d x = showFFloat d x ""

main :: IO ()
main = do
  putStrLn (f Nothing 1234.5)
  putStrLn (f Nothing 1)
  putStrLn (f Nothing 0)
  putStrLn (f Nothing 0.1)
  putStrLn (f Nothing 0.001)
  putStrLn (f Nothing 1.0e-4)
  putStrLn (f Nothing 1.0e7)
  putStrLn (f Nothing 1.0e21)
  putStrLn (f Nothing 123456789.125)
  putStrLn (f Nothing 1.25e-7)
  putStrLn (f Nothing (-1234.5))
  putStrLn (f Nothing (-0.03125))
  putStrLn (f Nothing (0.1 + 0.2))
  putStrLn (f Nothing (1 / 3))
  putStrLn (f (Just 2) 3.14159)
  putStrLn (f (Just 4) 3.14159)
  putStrLn (f (Just 3) 2)
  putStrLn (f (Just 1) 2.56)
  putStrLn (f (Just 1) 2.54)
  putStrLn (f (Just 2) 0.006)
  putStrLn (f (Just 2) 0.004)
  putStrLn (f (Just 3) 0.01)
  putStrLn (f (Just 1) 99.96)
  putStrLn (f (Just 2) 0.999)
  putStrLn (f (Just 2) 0.994)
  putStrLn (f (Just 2) 0)
  putStrLn (f (Just 5) 0)
  putStrLn (f (Just 1) 0)
  putStrLn (f (Just 2) 1.0e10)
  putStrLn (f (Just 3) 1.0e-10)
  putStrLn (f (Just 12) 1.0e-10)
  putStrLn (f (Just 1) (-2.56))
  putStrLn (f (Just 2) (-0.006))
  putStrLn (f (Just 3) (-1234.5678))
  putStrLn (f (Just 10) 1.5)
  putStrLn (f (Just 20) 0.1)
  putStrLn (f (Just 6) (1 / 3))
  putStrLn (f (Just 6) (2 / 3))
  putStrLn (f (Just 2) 1234567.891)
  putStrLn (showFFloat (Just 3) (3.14159 :: Float) "")
  putStrLn (showFFloat Nothing (0.1 :: Float) "")
  putStrLn (showFFloat Nothing (16777216 :: Float) "")
  putStrLn (showFFloat (Just 2) (19.999 :: Double) " EUR")
  putStrLn ((showFFloat (Just 1) (1.26 :: Double) . showString " < " . showFFloat (Just 1) (3.74 :: Double)) "")
