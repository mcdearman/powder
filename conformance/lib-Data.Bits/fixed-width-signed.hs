-- Haskell 2010 Report 15 (Data.Bits): Bits at Int8, Int16, Int32, Int64 (signed: arithmetic right shift)
module Main (main) where

import Data.Bits
import Data.Int

main :: IO ()
main = do
  print ("int8 and or xor", (12 :: Int8) .&. 10, (12 :: Int8) .|. 10, (12 :: Int8) `xor` 10)
  print ("int8 complement", complement (0 :: Int8), complement (127 :: Int8), complement (-128 :: Int8))
  print ("int8 shiftL into sign", (1 :: Int8) `shiftL` 7)
  print ("int8 shiftL overflow", (127 :: Int8) `shiftL` 1)
  print ("int8 shiftL drops high bits", (65 :: Int8) `shiftL` 2)
  print ("int8 shiftR arithmetic", (-128 :: Int8) `shiftR` 1, (-128 :: Int8) `shiftR` 7)
  print ("int8 shiftR positive", (127 :: Int8) `shiftR` 6)
  print ("int8 shift negative amount", shift (-16 :: Int8) (-2))
  print ("int8 isSigned", isSigned (0 :: Int8))
  print ("int16 and with negative", (-1 :: Int16) .&. 255)
  print ("int16 xor", (-1 :: Int16) `xor` 255)
  print ("int16 shiftL into sign", (1 :: Int16) `shiftL` 15)
  print ("int16 shiftL", (255 :: Int16) `shiftL` 8)
  print ("int16 shiftR arithmetic", (-32768 :: Int16) `shiftR` 15)
  print ("int16 complement", complement (32767 :: Int16))
  print ("int16 testBit sign", testBit (-1 :: Int16) 15, testBit (32767 :: Int16) 15)
  print ("int16 isSigned", isSigned (0 :: Int16))
  print ("int32 shiftL into sign", (1 :: Int32) `shiftL` 31)
  print ("int32 shiftL overflow", (65536 :: Int32) `shiftL` 15, (65537 :: Int32) `shiftL` 16)
  print ("int32 shiftR arithmetic", (minBound :: Int32) `shiftR` 31, (minBound :: Int32) `shiftR` 30)
  print ("int32 or", (minBound :: Int32) .|. maxBound)
  print ("int32 complement", complement (maxBound :: Int32) == minBound)
  print ("int32 setBit sign", setBit (0 :: Int32) 31)
  print ("int32 isSigned", isSigned (0 :: Int32))
  print ("int64 shiftL into sign", (1 :: Int64) `shiftL` 63 == minBound)
  print ("int64 shiftL", (1 :: Int64) `shiftL` 40)
  print ("int64 shiftR arithmetic", (minBound :: Int64) `shiftR` 62)
  print ("int64 shift negative amount", shift (minBound :: Int64) (-63))
  print ("int64 xor", (minBound :: Int64) `xor` (-1) == maxBound)
  print ("int64 clearBit sign", clearBit (-1 :: Int64) 63 == maxBound)
  print ("int64 bit", bit 33 :: Int64)
  print ("int64 isSigned", isSigned (0 :: Int64))
