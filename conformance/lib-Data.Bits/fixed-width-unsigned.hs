-- Haskell 2010 Report 15 (Data.Bits): Bits at Word, Word8, Word16, Word32, Word64 (unsigned: logical right shift)
module Main (main) where

import Data.Bits
import Data.Word

main :: IO ()
main = do
  print ("word8 and or xor", (12 :: Word8) .&. 10, (12 :: Word8) .|. 10, (12 :: Word8) `xor` 10)
  print ("word8 complement", complement (0 :: Word8), complement (255 :: Word8), complement (170 :: Word8))
  print ("word8 shiftL", (1 :: Word8) `shiftL` 7)
  print ("word8 shiftL drops high bits", (255 :: Word8) `shiftL` 4, (129 :: Word8) `shiftL` 1)
  print ("word8 shiftR logical", (200 :: Word8) `shiftR` 3, (255 :: Word8) `shiftR` 7)
  print ("word8 shift negative amount", shift (200 :: Word8) (-3))
  print ("word8 testBit", [testBit (170 :: Word8) i | i <- [0 .. 7]])
  print ("word8 isSigned", isSigned (0 :: Word8))
  print ("word16 complement", complement (0 :: Word16))
  print ("word16 shiftL", (255 :: Word16) `shiftL` 8, (65535 :: Word16) `shiftL` 15)
  print ("word16 shiftR logical", (65535 :: Word16) `shiftR` 15, (32768 :: Word16) `shiftR` 8)
  print ("word16 xor", (65535 :: Word16) `xor` 255)
  print ("word16 isSigned", isSigned (0 :: Word16))
  print ("word32 complement", complement (0 :: Word32))
  print ("word32 shiftL", (1 :: Word32) `shiftL` 31, (3 :: Word32) `shiftL` 31)
  print ("word32 shiftR logical", (maxBound :: Word32) `shiftR` 31, (maxBound :: Word32) `shiftR` 16)
  print ("word32 and mask", (305419896 :: Word32) .&. 65535)
  print ("word32 isSigned", isSigned (0 :: Word32))
  print ("word64 complement", complement (0 :: Word64))
  print ("word64 shiftL", (1 :: Word64) `shiftL` 63)
  print ("word64 shiftR logical", (maxBound :: Word64) `shiftR` 63, (maxBound :: Word64) `shiftR` 1)
  print ("word64 setBit top", setBit (0 :: Word64) 63)
  print ("word64 clearBit top", clearBit (maxBound :: Word64) 63)
  print ("word64 isSigned", isSigned (0 :: Word64))
  print ("word complement", complement (0 :: Word) == maxBound)
  print ("word shiftL", (1 :: Word) `shiftL` 63)
  print ("word shiftR logical", (maxBound :: Word) `shiftR` 60)
  print ("word bit", bit 10 :: Word)
  print ("word isSigned", isSigned (0 :: Word))
