-- Haskell 2010 Report 10.6 / 4.4.2: fixity resolution of Prelude operators; values depend on precedence and associativity
module Main (main) where

main :: IO ()
main = do
  print ("mul over add", 1 + 2 * 3, 2 * 3 + 1, (1 + 2) * 3)
  print ("left assoc minus", 10 - 3 - 2, 10 - (3 - 2))
  print ("left assoc div", 100 `div` 10 `div` 2, 100 `div` (10 `div` 2))
  print ("right assoc power", 2 ^ 3 ^ 2, (2 ^ 3) ^ 2)
  print ("power over mul", 2 * 3 ^ 2, (2 * 3) ^ 2)
  print ("div mod same level left", 17 `div` 5 `mod` 2, 17 `mod` 5 `div` 2, 17 `mod` 5 * 2)
  print ("quot rem with mul", 2 * 7 `quot` 3, 2 * 7 `rem` 3, 7 `rem` 4 * 2)
  print ("cons right assoc", 1 : 2 : 3 : [])
  print ("append right assoc", [1] ++ [2] ++ [3])
  print ("cons and append same level", 1 : [2] ++ [3], [0] ++ 1 : [2])
  print ("arith over cons", 1 + 1 : 2 * 2 : [])
  print ("comparison under arith", 1 + 1 == 2, 2 * 3 > 5, 1 + 2 < 2 * 2)
  print ("and over or", True || False && False, (True || False) && False)
  print ("comparison over and", 1 < 2 && 2 < 3, 1 == 1 || 1 == 2 && 2 == 3)
  print ("and right assoc lazy", False && undefined, True || undefined)
  print ("compose over application op", (negate . abs $ 3), (succ . succ . succ $ 0))
  print ("dollar right assoc", negate $ abs $ negate $ 3)
  print ("compose right assoc", ((+ 1) . (* 2) . subtract 3) 10)
  print ("compose over power", ((^ 2) . (+ 1)) 3)
  print ("elem level 4", 3 `elem` [1, 2] ++ [3], 1 + 1 `elem` [2], 5 `notElem` 1 : [2])
  print ("index level 9", [1, 2, 3] !! 1 + 1, [10, 20, 30] !! 2 * 2, 2 ^ [1, 2, 3] !! 2)
  print ("seq level 0", 1 `seq` 2 + 3, (1 :: Int) `seq` 'a' : "b")
  print ("bind left assoc", Just 1 >>= Just . (+ 1) >>= Just . (* 2))
  print ("then and bind", Just 1 >> Just 2 >>= Just . (+ 1))
  print ("reverse bind right assoc", Just . (+ 1) =<< Just . (* 2) =<< Just 5)
  print ("fractional", 1 / 2 / 2, 2 ** 3 ** 2, 8 / 2 * 4, 2 ^^ 2 ^ 2)
  print ("dollar bang", negate $! abs $! negate $! 3)
  print ("function application binds tightest", negate 3 + 4, succ 1 * 2, length [1, 2] ^ 2)
  print ("backquoted default infixl 9", 2 * 3 `max` 4, 10 `subtract` 3 `subtract` 1, 2 ^ 3 `min` 2)
