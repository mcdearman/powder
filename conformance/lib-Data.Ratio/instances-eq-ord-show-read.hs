-- Haskell 2010 Report 22 (Data.Ratio): Eq, Ord, Show and Read instances of Ratio (showsPrec at
-- precedence 7: parenthesised at 8 and above; components shown at precedence 8)
module Main (main) where

import Data.List (sort)
import Data.Ratio

main :: IO ()
main = do
  print ("eq", (1 % 2 :: Rational) == 2 % 4, (1 % 2 :: Rational) == 1 % 3, (1 % 2 :: Rational) /= 1 % 3)
  print ("eq signs", ((-1) % 2 :: Rational) == 1 % (-2), ((-1) % (-2) :: Rational) == 1 % 2)
  print ("eq with literal", (4 % 2 :: Rational) == 2, (3 % 4 :: Rational) == 0.75)
  print ("compare", compare (1 % 3) (1 % 2 :: Rational), compare (2 % 3) (1 % 2 :: Rational), compare (2 % 4) (1 % 2 :: Rational))
  print ("compare negatives", compare ((-1) % 2) ((-1) % 3 :: Rational), compare ((-1) % 2) (1 % 3 :: Rational))
  print ("ord operators", (1 % 3 :: Rational) < 1 % 2, (1 % 3 :: Rational) >= 1 % 2, (7 % 2 :: Rational) > 3, (7 % 2 :: Rational) <= 4)
  print ("max min", max (2 % 3) (3 % 5 :: Rational), min (2 % 3) (3 % 5 :: Rational))
  print ("sort", sort [1 % 2, (-1) % 3, 2 % 3, 0, 1 % 3, (-1) % 2, 1 :: Rational])
  print ("maximum minimum", maximum [3 % 7, 4 % 9, 5 % 11 :: Rational], minimum [3 % 7, 4 % 9, 5 % 11 :: Rational])
  putStrLn (show (3 % 4 :: Rational))
  putStrLn (show ((-3) % 4 :: Rational))
  putStrLn (show (3 % (-4) :: Rational))
  putStrLn (show (5 :: Rational))
  putStrLn (show (0 :: Rational))
  putStrLn (show (6 % 8 :: Ratio Int))
  putStrLn (showsPrec 7 (3 % 4 :: Rational) "")
  putStrLn (showsPrec 8 (3 % 4 :: Rational) "")
  putStrLn (showsPrec 8 ((-3) % 4 :: Rational) "")
  putStrLn (showsPrec 0 (3 % 4 :: Rational) " rest")
  print (Just (3 % 4 :: Rational))
  print (Just ((-3) % 4 :: Rational))
  print [1 % 2, (-3) % 4 :: Rational]
  print (1 % 2 :: Rational, 3 % 4 :: Ratio Int)
  print (Left (1 % 3) :: Either Rational Int)
  print ("read", (read "3 % 4" :: Rational))
  print ("read without spaces", (read "3%4" :: Rational))
  print ("read normalises", (read "6 % 8" :: Rational))
  print ("read negative numerator", (read "(-3) % 4" :: Rational))
  print ("read parenthesised", (read " ( 3 % 4 ) " :: Rational))
  print ("read Ratio Int", (read "5 % 10" :: Ratio Int))
  print ("read in Just", (read "Just (3 % 4)" :: Maybe Rational))
  print ("read list", (read "[1 % 2,(-3) % 4]" :: [Rational]))
  print ("read . show", all (\r -> read (show r) == r) [3 % 4, (-3) % 4, 0, 7, 22 % 7 :: Rational])
  print ("reads rest", (reads "3 % 4 rest" :: [(Rational, String)]))
  print ("readsPrec 8 needs parentheses", null (readsPrec 8 "3 % 4" :: [(Rational, String)]))
  print ("readsPrec 8 parenthesised", (readsPrec 8 "(3 % 4)" :: [(Rational, String)]))
  print ("reads rejects a bare integer", null (reads "3" :: [(Rational, String)]))
