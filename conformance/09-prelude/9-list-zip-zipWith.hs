-- Haskell 2010 Report 9 (PreludeList): zip and zipWith; the result is as long as the shorter list
module Main (main) where

main :: IO ()
main = do
  print ("zip", zip [1, 2, 3 :: Int] "abc")
  print ("zip left shorter", zip [1, 2 :: Int] "abcd")
  print ("zip right shorter", zip [1, 2, 3, 4 :: Int] "ab")
  print ("zip empty", zip ([] :: [Int]) "abc", zip "abc" ([] :: [Int]), zip ([] :: [Int]) ([] :: [Char]))
  print ("zip with infinite", zip [1 :: Int ..] "abc", zip "abc" (repeat True), zip "ab" (cycle [LT, GT]))
  print ("zip both infinite", take 3 (zip [1 :: Int ..] [10 :: Int, 20 ..]))
  print ("zip singleton", zip [()] [()], zip "a" "bcd")
  print ("zip empty left: right not forced", zip ([] :: [Int]) (undefined :: [Char]))
  print ("zip stops before bottom tail", zip [1 :: Int] ('a' : undefined), zip (1 : undefined) "" :: [(Int, Char)])
  print ("zip lazy in elements", length (zip [undefined, undefined :: Int] "ab"), map snd (zip [undefined, undefined :: Int] "ab"))
  print ("zip nested", zip (zip "ab" [1 :: Int ..]) [True, False], zip [[1 :: Int], []] ["x", "y"])
  print ("zip with itself", zip "abc" (tail "abc"), zip [1, 2, 3 :: Int] (reverse [1, 2, 3 :: Int]))
  print ("zip index", zip [0 :: Int ..] "hey", lookup 2 (zip [0 :: Int ..] "hey"))
  print ("zipWith", zipWith (+) [1, 2, 3 :: Int] [10, 20, 30], zipWith (,) "ab" [True, False])
  print ("zipWith unequal", zipWith (+) [1, 2, 3 :: Int] [10, 20], zipWith (+) [1 :: Int] [10, 20, 30])
  print ("zipWith empty", zipWith (+) ([] :: [Int]) [1, 2], zipWith (+) [1, 2] ([] :: [Int]), zipWith undefined ([] :: [Int]) ([] :: [Int]) :: [Int])
  print ("zipWith infinite", zipWith (*) [1 :: Int ..] [1, 2, 3], take 4 (zipWith (+) [1 :: Int ..] [100 ..]))
  print ("zipWith different types", zipWith replicate [1, 2, 3] "abc", zipWith (\c n -> fromEnum c + n) "ab" [1, 2 :: Int])
  print ("zipWith const", zipWith const "abc" [undefined, undefined :: Int], zipWith (flip const) [undefined :: Int] "z")
  print ("zipWith ($)", zipWith ($) [(+ 1), (* 2), negate] [10, 20, 30 :: Int])
  print ("zipWith comparisons", zipWith (<) [1, 5, 3 :: Int] [2, 4, 3], zipWith max "apz" "bbb", zipWith compare [1, 2 :: Int] [2, 1])
  print ("zip = zipWith (,)", zip "ab" [1, 2 :: Int] == zipWith (,) "ab" [1, 2])
  print ("fibs via zipWith", take 10 (let fibs = 0 : 1 : zipWith (+) fibs (tail fibs) in fibs :: [Integer]))
  print ("pairwise differences", (\xs -> zipWith (-) (tail xs) xs) [1, 4, 9, 16, 25 :: Int])
