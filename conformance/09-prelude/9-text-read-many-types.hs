-- Haskell 2010 Report 9 (PreludeText): read at many types, with surrounding whitespace and redundant parentheses
module Main (main) where

import Data.Ratio ((%))

main :: IO ()
main = do
  print ("Int", read "42" :: Int, read "-42" :: Int, read "0" :: Int, read "007" :: Int)
  print ("Int whitespace", read "  42" :: Int, read "42  " :: Int, read "\t42\n" :: Int)
  print ("Int parens", read "(42)" :: Int, read "((42))" :: Int, read " ( 42 ) " :: Int, read "(-42)" :: Int)
  print ("Int bounds", read "9223372036854775807" :: Int, read "-9223372036854775808" :: Int)
  print ("Integer", read "123456789012345678901234567890" :: Integer, read "-7" :: Integer, read "(0)" :: Integer)
  print ("Double", read "3.5" :: Double, read "-2.25" :: Double, read "3" :: Double, read "0.1" :: Double)
  print ("Double exponent", read "1e3" :: Double, read "1.5e2" :: Double, read "1e-2" :: Double, read "2.5E3" :: Double)
  print ("Double parens/space", read " ( 1.5 ) " :: Double, read "(-1.5)" :: Double)
  print ("Double special", read "Infinity" :: Double, isNaN (read "NaN" :: Double))
  print ("Float", read "0.5" :: Float, read "1.0e-2" :: Float, read "16777216" :: Float)
  print ("Rational", read "3 % 4" :: Rational, read "(-3) % 4" :: Rational, read " ( 6 % 8 ) " :: Rational)
  print ("Bool", read "True" :: Bool, read " False " :: Bool, read "(True)" :: Bool)
  print ("Ordering", read "LT" :: Ordering, read "EQ" :: Ordering, read " ( GT ) " :: Ordering)
  print ("unit", read "()" :: (), read " ( ) " :: (), read "(())" :: ())
  print ("Char", read "'a'" :: Char, read "'\\n'" :: Char, read "'\\''" :: Char, read " 'z' " :: Char, read "'\"'" :: Char)
  print ("Char escapes", read "'\\t'" :: Char, read "'\\65'" :: Char, read "'\\x41'" :: Char, read "'\\DEL'" :: Char, read "'\\\\'" :: Char)
  print ("String", read "\"hello\"" :: String, read "\"\"" :: String, read " \"sp ace\" " :: String)
  print ("String escapes", read "\"a\\tb\\n\"" :: String, read "\"q\\\"q\"" :: String, read "\"\\65\\&5\"" :: String, read "\"\\SO\\&H\"" :: String)
  print ("list", read "[1,2,3]" :: [Int], read "[]" :: [Int], read " [ 1 , 2,3 ] " :: [Int], read "[-1,(2)]" :: [Int])
  print ("list of lists", read "[[1],[],[2,3]]" :: [[Int]], read "[\"a\",\"b\"]" :: [String], read "[\"\"]" :: [String])
  print ("pair", read "(1,True)" :: (Int, Bool), read " ( 1 , True ) " :: (Int, Bool), read "((1,True))" :: (Int, Bool))
  print ("triple", read "(1,'a',\"s\")" :: (Int, Char, String), read "(-1,2.5,())" :: (Int, Double, ()))
  print ("nested tuples", read "((1,2),[(3,'x')])" :: ((Int, Int), [(Int, Char)]))
  print ("Maybe", read "Just 3" :: Maybe Int, read "Nothing" :: Maybe Int, read "Just (-3)" :: Maybe Int, read "(Just 3)" :: Maybe Int)
  print ("Maybe spacing", read "  Just   3  " :: Maybe Int, read "Just(3)" :: Maybe Int, read "(Just (3))" :: Maybe Int)
  print ("Maybe nested", read "Just (Just 3)" :: Maybe (Maybe Int), read "Just Nothing" :: Maybe (Maybe Int), read "Just [1,2]" :: Maybe [Int])
  print ("Maybe of things", read "Just \"s\"" :: Maybe String, read "Just (1,2)" :: Maybe (Int, Int), read "Just ()" :: Maybe (), read "Just 'c'" :: Maybe Char)
  print ("Either", read "Left 5" :: Either Int Bool, read "Right False" :: Either Int Bool, read "Left (-5)" :: Either Int Bool)
  print ("Either nested", read "Right (Just 2)" :: Either Int (Maybe Int), read "Left (Right 'x')" :: Either (Either Int Char) Int)
  print ("lists of structures", read "[Just 1,Nothing]" :: [Maybe Int], read "[Left 1,Right \"r\"]" :: [Either Int String], read "[(1,LT),(2,GT)]" :: [(Int, Ordering)])
  print ("read . show", all (\x -> read (show x) == x) [minBound, -1, 0, 1, maxBound :: Int], all (\x -> read (show x) == x) [0.1, -2.5, 1.0e-10, 1.0e22, 123456.789 :: Double])
  print ("read . show structures", read (show [Just (-1.5), Nothing]) == [Just (-1.5 :: Double), Nothing], read (show (3 % 4 :: Rational, "s", 'c')) == (3 % 4 :: Rational, "s", 'c'))
