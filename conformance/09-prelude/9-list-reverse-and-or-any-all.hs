-- Haskell 2010 Report 9 (PreludeList): reverse, and, or, any, all
module Main (main) where

main :: IO ()
main = do
  print ("reverse", reverse [1, 2, 3 :: Int], reverse "hello", reverse [[1, 2], [3 :: Int]])
  print ("reverse edge", reverse ([] :: [Int]), reverse "a", reverse "ab")
  print ("reverse twice", reverse (reverse "abc") == "abc", reverse [1 .. 1000 :: Int] == [1000, 999 .. 1])
  print ("reverse lazy in elements", length (reverse [undefined, undefined :: Int]), head (reverse [undefined, 2 :: Int]))
  print ("reverse palindrome", map (\s -> s == reverse s) ["", "a", "abba", "abc", "racecar"])
  print ("reverse of append", reverse ("ab" ++ "cd") == reverse "cd" ++ reverse "ab")
  print ("and", and [True, True], and [True, False], and [False, False], and [True])
  print ("and empty", and [])
  print ("and long", and (replicate 1000 True), and (replicate 1000 True ++ [False]))
  print ("or", or [True, True], or [True, False], or [False, False], or [False])
  print ("or empty", or [])
  print ("or long", or (replicate 1000 False), or (replicate 1000 False ++ [True]))
  print ("and/or stop early", and [False, undefined], or [True, undefined])
  print ("any", any even [1, 3, 5 :: Int], any even [1, 4, 5 :: Int], any (== 'x') "abc", any (== 'b') "abc")
  print ("any empty", any even ([] :: [Int]), any undefined ([] :: [Int]))
  print ("any stops early", any even [1, 2, undefined :: Int], any (const True) [undefined :: Int])
  print ("all", all even [2, 4, 6 :: Int], all even [2, 3, 6 :: Int], all (== 'a') "aaa", all (< 'd') "abcd")
  print ("all empty", all even ([] :: [Int]), all undefined ([] :: [Int]))
  print ("all stops early", all even [2, 3, undefined :: Int], all (const False) [undefined :: Int])
  print ("any = or . map", any odd [2, 4, 5 :: Int] == or (map odd [2, 4, 5 :: Int]))
  print ("all = and . map", all odd [1, 3, 4 :: Int] == and (map odd [1, 3, 4 :: Int]))
  print ("duality", not (any even [1, 3 :: Int]) == all (not . even) [1, 3 :: Int])
  print ("nested", all (any even) [[1, 2], [4], [3, 5, 6 :: Int]], any (all even) [[1, 2], [3 :: Int]], all null ["", ""])
  print ("and of comparisons", and (zipWith (<=) [1, 2, 3 :: Int] [2, 3, 4]), or (zipWith (>) [1, 2, 3 :: Int] [2, 3, 4]))
