-- Haskell 2010 Report 9 (PreludeList): map, (++), filter, concat, concatMap
module Main (main) where

main :: IO ()
main = do
  print ("map", map (+ 1) [1, 2, 3 :: Int], map show [1, 2 :: Int], map fst [(1 :: Int, 'a')])
  print ("map empty", map (+ 1) ([] :: [Int]), map undefined ([] :: [Int]) :: [Int])
  print ("map infinite", take 4 (map (* 2) [1 :: Int ..]))
  print ("map lazy elements", length (map undefined "abc" :: [Int]), head (map (* 2) (3 : undefined)) :: Int)
  print ("map nested", map (map negate) [[1, 2], [], [3 :: Int]])
  print ("map composition", map (succ . succ) "abc" == map succ (map succ "abc"))
  print ("++", [1, 2] ++ [3, 4 :: Int], "ab" ++ "cd", [] ++ [1 :: Int], [1 :: Int] ++ [], ([] :: [Int]) ++ [])
  print ("++ infinite right", take 5 ([1, 2] ++ [10 :: Int ..]))
  print ("++ infinite left", take 3 ([1 :: Int ..] ++ undefined))
  print ("++ lazy in second", head ("a" ++ undefined), take 2 ("ab" ++ undefined))
  print ("++ prefix and sections", (++) "x" "y", ("<" ++) "x", (++ ">") "x")
  print ("filter", filter even [1 .. 10 :: Int], filter (> 'b') "abcda", filter (const True) "xyz")
  print ("filter none/all/empty", filter (const False) "xyz", filter odd [2, 4 :: Int], filter even ([] :: [Int]))
  print ("filter infinite", take 3 (filter ((== 0) . (`mod` 7)) [1 :: Int ..]))
  print ("filter keeps order and duplicates", filter (/= ' ') "a b  a c")
  print ("filter twice", filter even (filter (> 3) [1 .. 10 :: Int]) == filter (\x -> even x && x > 3) [1 .. 10])
  print ("concat", concat [[1, 2], [3], [], [4, 5 :: Int]], concat ["ab", "", "c"])
  print ("concat edge", concat ([] :: [[Int]]), concat [[], [] :: [Int]], concat [[1 :: Int]])
  print ("concat infinite outer", take 5 (concat (repeat [1, 2 :: Int])))
  print ("concat infinite inner", take 3 (concat [[1 :: Int ..], undefined]))
  print ("concat nested", concat (concat [[[1], [2, 3]], [[4 :: Int]]]))
  print ("concatMap", concatMap (\x -> [x, x * 10]) [1, 2, 3 :: Int], concatMap show [1, 22, 333 :: Int])
  print ("concatMap edge", concatMap (replicate 2) "", concatMap (const "") "abc", concatMap (: []) "abc")
  print ("concatMap infinite", take 6 (concatMap (\x -> [x, negate x]) [1 :: Int ..]))
  print ("concatMap = concat . map", concatMap words ["a b", "c"] == concat (map words ["a b", "c"]))
  print ("concatMap varying lengths", concatMap (\n -> replicate n n) [0, 1, 2, 3 :: Int])
