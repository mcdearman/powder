-- Haskell 2010 Report 9: class Enum at Char, Bool, Ordering and () (all eight methods; enumFrom/enumFromThen stop at the bounds)
module Main (main) where

main :: IO ()
main = do
  print ("Char succ/pred", succ 'a', pred 'b', succ '9', pred 'A')
  print ("Char fromEnum", fromEnum 'a', fromEnum 'A', fromEnum '0', fromEnum '\0', fromEnum '\n')
  print ("Char toEnum", toEnum 97 :: Char, toEnum 48 :: Char, toEnum 32 :: Char)
  print ("Char max", fromEnum (maxBound :: Char), toEnum 1114111 == (maxBound :: Char))
  print ("Char enumFromTo", enumFromTo 'a' 'e', ['x' .. 'z'], ['c' .. 'a'], ['m' .. 'm'])
  print ("Char enumFromThenTo", enumFromThenTo 'a' 'c' 'i', ['a', 'c' .. 'h'], ['e', 'c' .. 'a'], ['z', 'y' .. 'v'])
  print ("Char enumFrom", take 3 (enumFrom 'x'), take 3 ['0' ..])
  print ("Char enumFromThen", take 3 (enumFromThen 'a' 'd'), take 3 ['z', 'x' ..])
  print ("Char enumFrom bounded", length [pred (pred maxBound) :: Char ..], last ['a' ..] == maxBound)
  print ("Char enumFromThen bounded", length ['\5', '\3' ..], map fromEnum ['\5', '\3' ..])
  print ("Char whole range", length ['\0' ..])
  print ("Bool succ/pred", succ False, pred True)
  print ("Bool from/to", fromEnum False, fromEnum True, toEnum 0 :: Bool, toEnum 1 :: Bool)
  print ("Bool enumFrom", enumFrom False, enumFrom True, [False ..])
  print ("Bool enumFromThen", enumFromThen False True, enumFromThen True False, [True, False ..])
  print ("Bool enumFromTo", enumFromTo False True, enumFromTo True False, [True .. True])
  print ("Bool enumFromThenTo", enumFromThenTo False True True, enumFromThenTo True False False, [False, True .. False])
  print ("Ordering succ/pred", succ LT, succ EQ, pred GT, pred EQ)
  print ("Ordering from/to", map fromEnum [LT, EQ, GT], map toEnum [0, 1, 2] :: [Ordering])
  print ("Ordering enumFrom", enumFrom LT, [EQ ..], [GT ..])
  print ("Ordering enumFromThen", enumFromThen LT GT, [GT, EQ ..], [LT, EQ ..], [EQ, LT ..])
  print ("Ordering enumFromTo", [LT .. GT], [EQ .. GT], [GT .. LT])
  print ("Ordering enumFromThenTo", [LT, GT .. GT], [GT, EQ .. LT], [GT, EQ .. EQ], [LT, EQ .. LT])
  print ("unit", fromEnum (), toEnum 0 :: (), enumFrom (), [() .. ()], enumFromTo () ())
  print ("unit then", take 3 (enumFromThen () ()), take 2 (enumFromThenTo () () ()))
