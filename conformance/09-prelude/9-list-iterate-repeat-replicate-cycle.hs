-- Haskell 2010 Report 9 (PreludeList): iterate, repeat, replicate, cycle
module Main (main) where

main :: IO ()
main = do
  print ("iterate", take 5 (iterate (* 2) (1 :: Int)), take 4 (iterate (++ "!") "hi"))
  print ("iterate first is seed", head (iterate (undefined :: Int -> Int) 7), take 1 (iterate succ 'a'))
  print ("iterate take 0", take 0 (iterate (+ 1) (0 :: Int)))
  print ("iterate index", iterate (+ 3) (0 :: Int) !! 10, iterate not True !! 5)
  print ("iterate on pairs", map fst (take 8 (iterate (\(a, b) -> (b, a + b)) (0 :: Integer, 1))))
  print ("iterate takeWhile", takeWhile (< 100) (iterate (\x -> x * x + 1) (1 :: Int)))
  print ("iterate id", take 3 (iterate id 'k'))
  print ("repeat", take 3 (repeat 'x'), take 2 (repeat [1 :: Int]), take 0 (repeat ()))
  print ("repeat lazy element", length (take 4 (repeat (undefined :: Int))))
  print ("repeat with zip", zip "abc" (repeat (0 :: Int)), zipWith const (repeat 'z') "four")
  print ("repeat index", repeat (5 :: Int) !! 12345)
  print ("replicate", replicate 3 'x', replicate 2 [1 :: Int], replicate 1 True)
  print ("replicate zero", replicate 0 'x', replicate 0 (undefined :: Int))
  print ("replicate negative", replicate (-1) 'x', replicate (-100) (1 :: Int), replicate minBound 'q')
  print ("replicate lazy element", length (replicate 5 (undefined :: Int)))
  print ("replicate = take n . repeat", replicate 4 'a' == take 4 (repeat 'a'))
  print ("replicate nested", replicate 2 (replicate 3 '-'), concat (replicate 3 "ab"))
  print ("replicate length", length (replicate 100000 ()), sum (replicate 10 (7 :: Int)))
  print ("cycle", take 7 (cycle [1, 2, 3 :: Int]), take 5 (cycle "ab"), take 3 (cycle [()]))
  print ("cycle singleton", take 3 (cycle "x"))
  print ("cycle infinite input", take 4 (cycle [1 :: Int ..]))
  print ("cycle take less than period", take 2 (cycle "abcdef"), take 0 (cycle "abc"))
  print ("cycle index", cycle "abc" !! 3000, cycle [0 :: Int, 1] !! 99999)
  print ("cycle with zip", zip [1 .. 5 :: Int] (cycle "xy"), zipWith (*) [1 .. 6] (cycle [1, -1 :: Int]))
  print ("cycle partial input", take 3 (cycle ('a' : 'b' : 'c' : undefined)))
  print ("mixed", take 6 (concat (repeat "ab")) == take 6 (cycle "ab"), take 5 (iterate (const 'r') 'r') == replicate 5 'r')
