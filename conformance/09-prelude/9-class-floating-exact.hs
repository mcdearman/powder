-- Haskell 2010 Report 9: class Floating; results that are exact (pi constant, functions at 0 or 1, exact powers and roots)
module Main (main) where

main :: IO ()
main = do
  print ("pi Double", pi :: Double)
  print ("pi Float", pi :: Float)
  print ("exp", exp 0 :: Double, exp 0 :: Float)
  print ("log", log 1 :: Double, log 1 :: Float)
  print ("sqrt", sqrt 4 :: Double, sqrt 0 :: Double, sqrt 1 :: Double, sqrt 6.25 :: Double, sqrt 16 :: Float)
  print ("sqrt 2", sqrt 2 :: Double, sqrt 2 :: Float)
  print ("sqrt negative is NaN", isNaN (sqrt (-1) :: Double))
  print ("**", 2 ** 10 :: Double, 2 ** 0 :: Double, 4 ** 0.5 :: Double, 2 ** (-1) :: Double, 2 ** 3 :: Float)
  print ("sin", sin 0 :: Double, sin 0 :: Float)
  print ("cos", cos 0 :: Double, cos 0 :: Float)
  print ("tan", tan 0 :: Double)
  print ("asin", asin 0 :: Double)
  print ("acos", acos 1 :: Double)
  print ("atan", atan 0 :: Double)
  print ("sinh", sinh 0 :: Double)
  print ("cosh", cosh 0 :: Double)
  print ("tanh", tanh 0 :: Double)
  print ("log of zero", log 0 :: Double, isInfinite (log 0 :: Double))
  print ("exp overflow", exp 1000 :: Double, exp (-1000) :: Double)
