module Main (main) where

import Data.Ratio ((%))

main :: IO ()
main = do
  putStrLn (show (0 :: Int) ++ " " ++ show (42 :: Int) ++ " " ++ show (-42 :: Int))
  putStrLn (show (minBound :: Int) ++ " " ++ show (maxBound :: Int))
  putStrLn (show (2 ^ (100 :: Int) :: Integer) ++ " " ++ show (negate (2 ^ (100 :: Int)) :: Integer))
  putStrLn (show True ++ " " ++ show False)
  putStrLn (show LT ++ " " ++ show EQ ++ " " ++ show GT)
  putStrLn (show ())
  putStrLn (show (1.0 :: Double) ++ " " ++ show (-1.5 :: Double) ++ " " ++ show (0.1 :: Double) ++ " " ++ show (0 :: Double))
  putStrLn (show (123456.789 :: Double) ++ " " ++ show (0.1 + 0.2 :: Double) ++ " " ++ show (1 / 3 :: Double))
  putStrLn (show (1.0e7 :: Double) ++ " " ++ show (9999999 :: Double) ++ " " ++ show (12345678.9 :: Double))
  putStrLn (show (0.1 :: Double) ++ " " ++ show (0.09 :: Double) ++ " " ++ show (1.0e-2 :: Double) ++ " " ++ show (1.5e-10 :: Double))
  putStrLn (show (1.0e100 :: Double) ++ " " ++ show (5.0e-324 :: Double) ++ " " ++ show (1.7976931348623157e308 :: Double))
  putStrLn (show (1 / 0 :: Double) ++ " " ++ show (-1 / 0 :: Double) ++ " " ++ show (-0.0 :: Double))
  putStrLn (show (1.0 :: Float) ++ " " ++ show (0.1 :: Float) ++ " " ++ show (1 / 3 :: Float) ++ " " ++ show (1.0e10 :: Float))
  putStrLn (show (16777216 :: Float) ++ " " ++ show (3.4028235e38 :: Float) ++ " " ++ show (-2.5e-3 :: Float))
  putStrLn (show (3 % 4 :: Rational) ++ " | " ++ show (-3 % 4 :: Rational) ++ " | " ++ show (5 :: Rational))
  putStrLn (show [1, 2, 3 :: Int] ++ " " ++ show ([] :: [Int]) ++ " " ++ show [[1], [], [2, 3 :: Int]])
  putStrLn (show [-1, -2 :: Int] ++ " " ++ show [-1.5 :: Double] ++ " " ++ show [True, False])
  putStrLn (show (1 :: Int, 'a') ++ " " ++ show (1 :: Int, 2.5 :: Double, "s") ++ " " ++ show ((), ((), ())))
  putStrLn (show (-1 :: Int, -2 :: Int) ++ " " ++ show (-1.5 :: Double, [-1 :: Int]))
  putStrLn (show (1 :: Int, 'b', "c", 4.0 :: Double, [5 :: Int], (6 :: Int, 7 :: Int), ()))
  putStrLn (show (Just 3 :: Maybe Int) ++ " " ++ show (Nothing :: Maybe Int) ++ " " ++ show (Just (-3) :: Maybe Int))
  putStrLn (show (Just (Just 1) :: Maybe (Maybe Int)) ++ " " ++ show (Just Nothing :: Maybe (Maybe Int)))
  putStrLn (show (Just "s") ++ " " ++ show (Just 'c') ++ " " ++ show (Just [1 :: Int]) ++ " " ++ show (Just (1 :: Int, 2 :: Int)) ++ " " ++ show (Just ()))
  putStrLn (show (Just (-1.5) :: Maybe Double) ++ " " ++ show (Just (3 % 4) :: Maybe Rational) ++ " " ++ show (Just (Left 1) :: Maybe (Either Int Int)))
  putStrLn (show (Left 1 :: Either Int Bool) ++ " " ++ show (Right True :: Either Int Bool) ++ " " ++ show (Left (-1) :: Either Int Bool))
  putStrLn (show (Right (Just 2) :: Either Int (Maybe Int)) ++ " " ++ show (Left (Right 'x') :: Either (Either Int Char) Int))
  putStrLn (show [Just (-1), Nothing :: Maybe Int] ++ " " ++ show [Left 1, Right "r" :: Either Int String])
  putStrLn (show (Just True, [Just LT], Left () :: Either () Int))
  putStrLn (show [(1 :: Int, "one"), (2, "two")] ++ " " ++ show ([] :: [(Int, String)]) ++ " " ++ show [()])
