-- Haskell 2010 Report 18 (Data.Int): Int, Int8, Int16, Int32, Int64 bounds (Bounded) and modular
-- (two's complement wraparound) arithmetic (Num)
module Main (main) where

import Data.Int

main :: IO ()
main = do
  print ("Int8 bounds", (minBound :: Int8), (maxBound :: Int8))
  print ("Int16 bounds", (minBound :: Int16), (maxBound :: Int16))
  print ("Int32 bounds", (minBound :: Int32), (maxBound :: Int32))
  print ("Int64 bounds", (minBound :: Int64), (maxBound :: Int64))
  print ("Int bounds", (minBound :: Int), (maxBound :: Int))
  print ("Int8 max plus one", (maxBound :: Int8) + 1)
  print ("Int8 min minus one", (minBound :: Int8) - 1)
  print ("Int8 add wraps", (100 :: Int8) + 100)
  print ("Int8 multiply wraps", (100 :: Int8) * 3, (16 :: Int8) * 16, (-128 :: Int8) * (-1))
  print ("Int8 negate minBound", negate (minBound :: Int8))
  print ("Int8 abs", abs (-5 :: Int8), abs (minBound :: Int8), abs (maxBound :: Int8))
  print ("Int8 signum", signum (-5 :: Int8), signum (0 :: Int8), signum (5 :: Int8))
  print ("Int8 fromInteger wraps", (fromInteger 128 :: Int8), (fromInteger 255 :: Int8), (fromInteger 256 :: Int8), (fromInteger (-129) :: Int8))
  print ("Int8 power", (2 :: Int8) ^ (7 :: Int), (2 :: Int8) ^ (8 :: Int), (3 :: Int8) ^ (5 :: Int))
  print ("Int16 max plus one", (maxBound :: Int16) + 1)
  print ("Int16 min minus one", (minBound :: Int16) - 1)
  print ("Int16 multiply wraps", (300 :: Int16) * 300, (256 :: Int16) * 128)
  print ("Int16 negate abs", negate (minBound :: Int16), abs (minBound :: Int16))
  print ("Int16 fromInteger wraps", (fromInteger 65535 :: Int16), (fromInteger 40000 :: Int16))
  print ("Int32 max plus one", (maxBound :: Int32) + 1)
  print ("Int32 min minus one", (minBound :: Int32) - 1)
  print ("Int32 multiply wraps", (65536 :: Int32) * 65536, (100000 :: Int32) * 100000)
  print ("Int32 power", (2 :: Int32) ^ (31 :: Int), (2 :: Int32) ^ (30 :: Int))
  print ("Int32 fromInteger wraps", (fromInteger (2 ^ (32 :: Int) + 7) :: Int32))
  print ("Int64 max plus one", (maxBound :: Int64) + 1)
  print ("Int64 min minus one", (minBound :: Int64) - 1)
  print ("Int64 multiply wraps", (4294967296 :: Int64) * 4294967296, (3037000500 :: Int64) * 3037000500)
  print ("Int64 power", (2 :: Int64) ^ (63 :: Int), (2 :: Int64) ^ (62 :: Int))
  print ("Int64 fromInteger wraps", (fromInteger (2 ^ (64 :: Int) + 5) :: Int64), (fromInteger (2 ^ (63 :: Int)) :: Int64))
  print ("Int max plus one", (maxBound :: Int) + 1 == minBound)
  print ("Int min minus one", (minBound :: Int) - 1 == maxBound)
  print ("Int negate minBound", negate (minBound :: Int) == minBound)
  print ("Int multiply wraps", (maxBound :: Int) * 2)
  print ("sum wraps", sum (replicate 3 (100 :: Int8)))
  print ("product wraps", product [1 .. 6 :: Int8])
